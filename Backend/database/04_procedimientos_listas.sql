USE CookFlow;
GO

ALTER TABLE LISTA_COMPRA ADD LCnombre VARCHAR(100) NULL;
GO

UPDATE LISTA_COMPRA
SET LCnombre = 'Lista del ' + CONVERT(VARCHAR(10), LCfecha, 103)
WHERE LCnombre IS NULL;
GO

CREATE OR ALTER PROCEDURE SP_GetListasUsuario @USid INT AS
BEGIN
    SET NOCOUNT ON;
    SELECT LCid, LCnombre, LCfecha, LCpax FROM LISTA_COMPRA
    WHERE USid = @USid ORDER BY LCfecha DESC, LCid DESC;
END
GO

CREATE OR ALTER PROCEDURE SP_GetListaById @LCid INT, @USid INT AS
BEGIN
    SET NOCOUNT ON;
    SELECT LCid, LCnombre, LCfecha, LCpax FROM LISTA_COMPRA WHERE LCid = @LCid AND USid = @USid;
END
GO

CREATE OR ALTER PROCEDURE SP_InsertLista @USid INT, @pax INT = 1, @nombre VARCHAR(100) = NULL AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @n VARCHAR(100) = NULLIF(LTRIM(RTRIM(@nombre)), '');
    IF @n IS NULL SET @n = 'Lista del ' + CONVERT(VARCHAR(10), GETDATE(), 103);
    INSERT INTO LISTA_COMPRA (USid, LCpax, LCnombre) VALUES (@USid, @pax, @n);
    SELECT SCOPE_IDENTITY() AS id;
END
GO

CREATE OR ALTER PROCEDURE SP_UpdateLista @LCid INT, @USid INT, @nombre VARCHAR(100) = NULL AS
BEGIN
    SET NOCOUNT ON;
    UPDATE LISTA_COMPRA
    SET LCnombre = ISNULL(NULLIF(LTRIM(RTRIM(@nombre)), ''),
                          'Lista del ' + CONVERT(VARCHAR(10), LCfecha, 103))
    WHERE LCid = @LCid AND USid = @USid;
    SELECT @@ROWCOUNT AS filas;
END
GO