CREATE OR ALTER PROCEDURE SP_GetRecetaById @RECid INT
AS BEGIN
    SET NOCOUNT ON;
    SELECT * FROM RECETAS WHERE RECid = @RECid;
END
GO

CREATE OR ALTER PROCEDURE SP_UpdateReceta
    @RECid INT, @titulo VARCHAR(150), @descripcion VARCHAR(MAX),
    @imagen VARCHAR(255), @tiempo INT, @dificultad VARCHAR(50), @CAid INT
AS BEGIN
    SET NOCOUNT ON;
    UPDATE RECETAS
    SET RECtitulo = @titulo, RECdescripcion = @descripcion, RECimagen = @imagen,
        RECtiempo = @tiempo, RECdificultad = @dificultad, CAid = @CAid
    WHERE RECid = @RECid;
    SELECT @@ROWCOUNT AS filas;
END
GO

CREATE OR ALTER PROCEDURE SP_DeleteReceta @RECid INT
AS BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;
        DELETE FROM FAVORITOS_RECETAS    WHERE RECid = @RECid;
        DELETE FROM RECETA_INGREDIENTES  WHERE RECid = @RECid;
        DELETE FROM RECETAS              WHERE RECid = @RECid;
        DECLARE @filas INT = @@ROWCOUNT;
        COMMIT TRANSACTION;
        SELECT @filas AS filas;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO

