CREATE OR ALTER PROCEDURE SP_DeleteUsuario @USid INT AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;
        DELETE FROM FAVORITOS_RECETAS WHERE USid = @USid;
        DELETE FROM RESTAURANTES_VISITADOS WHERE USid = @USid;
        DELETE FROM LISTA_COMPRA_ITEMS WHERE LCid IN (SELECT LCid FROM LISTA_COMPRA WHERE USid = @USid);
        DELETE FROM LISTA_COMPRA WHERE USid = @USid;
        -- Sus recetas (y lo que cuelga de ellas)
        DELETE FROM FAVORITOS_RECETAS   WHERE RECid IN (SELECT RECid FROM RECETAS WHERE USid = @USid);
        DELETE FROM RECETA_INGREDIENTES WHERE RECid IN (SELECT RECid FROM RECETAS WHERE USid = @USid);
        DELETE FROM RECETAS WHERE USid = @USid;
        DELETE FROM USUARIOS WHERE USid = @USid;
        DECLARE @filas INT = @@ROWCOUNT;
        COMMIT TRANSACTION;
        SELECT @filas AS filas;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO

